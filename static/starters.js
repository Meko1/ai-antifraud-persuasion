/* 第一轮的候选开场句。**只在第一轮出现，只是"点一下填进输入框"的辅助，
 * 不是选择题**——`say` 输入框全程都在，这几条填进去之后玩家还能删、
 * 还能改、还能干脆不点直接自己打字。
 *
 * ## 为什么只有第一轮
 *
 * POSITIONING「不做什么」那条红线管的是"每轮给候选句"——真给了，
 * 作品和公益 H5 就长一个样，"对方是活的"这条差异化资产当场作废。
 * 但红线挡的是**每一轮**，不是"完全不能有一个字提示"：第一轮是唯一一个
 * 玩家面前**什么上下文都没有**的时刻——对方一句话都还没说，无从"读时机"，
 * 这时候的难处是"不知从何开口"，不是"不知道该不该顺着对方的话往下接"。
 * 从第二轮起，对方已经说了话，回什么该读他刚说的那句，这时候再给候选句
 * 就是真正的泄题——所以这份表只服务第一轮，`chat.js` 的 `playTurn()`
 * 一进入第一轮就会把这块清掉。
 *
 * ## 内容怎么定
 *
 * 三条一组，每组分别对应「锚定真实用途」「苏格拉底式提问」「支持自主」
 * 这三把钥匙——选这三把不是随意的：它们是七把里**不需要对方已经说过话
 * 也能开口**的那几把（"指出内部矛盾"要有矛盾可指，"反映式倾听"要有情绪
 * 可倾听，两者都要求对方先说了什么，做不成开场白）。
 *
 * 每条都按这一局真实的剧本事实写（金额、平台名、人物关系），照的是
 * `app/scenarios/*.py` 里 `script`/`context` 字段那份事实——**不能凭空
 * 编一句"听着像"的话**，那是这个仓库从第一天就不许做的事。
 */
