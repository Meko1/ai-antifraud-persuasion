"""落库前的脱敏。

服务端此前一条对局记录都不存（ADR-0003），因此这个模块以前不需要存在。
转向 C 端异动干预之后要落对局数据（ADR-0006），**落之前必须过这一层**。

## 它和 app/safety.py 不是一回事

两个模块都在用正则删东西，但方向、对象、动作全都相反，混用会同时做砸两件事：

|            | safety.py            | 本模块                     |
|------------|----------------------|----------------------------|
| 管哪一侧   | 模型**输出**给玩家   | 玩家**输入**落进库里       |
| 防的是什么 | 现场直播说出真实标的 | 把真人的身份信息存下来     |
| 命中之后   | **整句**换成兜底台词 | **只挖掉那一段**，句子留着 |

最后一行是这里最要紧的取舍。**留存的唯一理由是拿它训分类器**
（ADR-0006「为什么要存」），而整句替换会把样本本身毁掉：
「我手机 138xxxx0000 你打给我」整句换掉，剩下的是一条没有标注价值的空记录；
挖成「我手机 [手机号] 你打给我」，这条样本照样能标 socratic_question。

## 脱敏不了的东西，写在明处

- **姓名**：中文姓名没有可靠的形状。能抓的只有自述句式（"我叫 X""我姓 X"），
  夹在句子中间的一律抓不到。收紧到能抓住它，就一定会误伤剧本里的人名
  （王老师、小雨、月娥姐），而那些是判分要用的内容。
- **病史、家庭关系、职业细节**这类自由文本同理：没有形状，只有语义。
  正则做不了语义。

**所以脱敏不是唯一的防线，留存范围才是**：只存玩家发言与判定结果，
账号、持仓、身份、设备一个字段都不进库（ADR-0006 §范围）。
一层挡不住的，靠"根本没往那儿存"挡。

**而挡不住的那部分，界面上就不许承诺挡得住。** 告知文案 2026-08-23 从
「账号、持仓与身份信息不会被记录」改成了「我们不会主动记录…你输入的内容
会经过自动去标识处理后留存」——承诺从"结果"退回"动作"
（见 app/transcripts.py 的 `DISCLOSURE_RETENTION`）。做不到的承诺，
在真实 C 端接入之后就是一份监管材料。

## 2026-08-23 补的三条，各自堵一个实测漏项

1. **带分隔符的号码**（`138 1234 5678`、`6222-0212-3456-7890`）。
   这是最要命的一条：它不需要任何技巧，用户顺手打个空格就绕过了原来那组
   规则，而原来那句告知还写着"不会被记录"。做法是**先归一化再匹配**，
   见 `_SPACED_DIGITS`。
2. **住址**。有形状（省市区路号 + 小区楼单元室），可以抓。
3. **工作单位**。同样有句式（"在 X 上班/工作"、"我们单位是 X"）。

持仓名称**没有加**，而且不打算加：股票名与普通词汇无法区分（"平安""长城"
"东方财富"），抓它一定会把正常对话挖成筛子。它属于上面"挡不住"那一栏，
靠告知说清楚，不靠正则假装。

## 金额刻意不脱敏

三十万、十万、两万八是**剧本里的虚构金额**，也是判分要认的内容
（`anchor_real_purpose` 判的就是他有没有把钱说回具体用途）。
脱掉它，这份语料就不能用来训分类器了——而那是留存的全部理由。
"""

from __future__ import annotations

import re
from typing import Tuple

# 落库的单条上限。接口层已经限到 200 字（`MAX_UTTERANCE_CHARS`），
# 这里再拦一道是因为**台词那一侧没有这个限制**：模型偶尔会飘成大段旁白，
# 而它同样要落库。截断不是省空间，是防止一条畸形记录把这一列撑爆。
MAX_CHARS = 600

# 占位符统一带方括号，肉眼一扫就知道这里被挖过。
# 不用 `***`：星号在真实语料里本来就出现（"这票***"），分不清是谁打的。
_RULES: Tuple[Tuple[re.Pattern, str], ...] = (
    # 邮箱要排在外链前面：不然 `@` 后面那截先被当域名挖掉，剩一个孤零零的用户名
    (re.compile(r"[\w.+-]+@[\w-]+\.[\w.-]+"), "[邮箱]"),
    # 身份证：18 位（末位可能是 X）与老式 15 位。**必须排在银行卡前面**，
    # 两条的数字长度区间挨着，顺序反了 18 位会先被当成卡号
    (re.compile(r"(?<!\d)\d{17}[\dXx](?!\d)"), "[身份证]"),
    (re.compile(r"(?<!\d)\d{15}(?!\d)"), "[身份证]"),
    # 手机号
    (re.compile(r"(?<!\d)1[3-9]\d{9}(?!\d)"), "[手机号]"),
    # 银行卡 / 证券账户：13~19 位连续数字。
    # **金额撞不上这一条**：剧本里最大的数是 300000，六位
    (re.compile(r"(?<!\d)\d{13,19}(?!\d)"), "[账号]"),
    # 外链
    (
        re.compile(r"(https?://\S+|www\.\S+|\b[\w-]+\.(?:com|cn|net|org)\b\S*)", re.IGNORECASE),
        "[链接]",
    ),
    # 微信号 / QQ 号。带前缀词才算——不带前缀的一串字母数字太常见了
    (
        re.compile(r"(?:微信|weixin|wechat|vx|wx|qq)\s*(?:号)?\s*[:：]?\s*[A-Za-z0-9_-]{5,}", re.IGNORECASE),
        "[联系方式]",
    ),
    # 姓名，**只认自述句式，且要姓得像个姓**。理由见模块顶部：这一条注定漏，
    # 写在这里是因为漏和不做是两回事——用户主动打出"我叫张伟"是最容易发生、
    # 也最该挖掉的一种。
    #
    # 姓氏门槛是为了治误伤。只看"我是＋两三个字"的话，「我是投顾」「我是新来的」
    # 一并被挖掉，而那些是判分要读的正常话。挂上百家姓之后，
    # 代价只剩「我是李经理」这类**看起来就是名字**的说法被一并挖掉——
    # 那一句本来也不带任何分类信号，挖了不心疼。
    (
        re.compile(
            r"(我叫|我姓|本人叫|我是)\s*"
            r"([赵钱孙李周吴郑王冯陈褚卫蒋沈韩杨朱秦尤许何吕施张孔曹严华金魏陶姜"
            r"戚谢邹喻柏水窦章云苏潘葛奚范彭郎鲁韦昌马苗凤花方俞任袁柳酆鲍史唐"
            r"费廉岑薛雷贺倪汤滕殷罗毕郝邬安常乐于时傅皮卞齐康伍余元卜顾孟平黄"
            r"和穆萧尹姚邵湛汪祁毛禹狄米贝明臧计伏成戴谈宋茅庞熊纪舒屈项祝董梁"
            r"杜阮蓝闵席季麻强贾路娄危江童颜郭梅盛林刁钟徐邱骆高夏蔡田樊胡凌霍"
            r"虞万支柯昝管卢莫柯房裘缪干解应宗丁宣贲邓郁单杭洪包诸左石崔吉钮龚]"
            r"[一-龥]{0,2})(?=[\s，。,.!！?？、]|$)"
        ),
        r"\1[姓名]",
    ),
)

# ── 带分隔符的号码 ────────────────────────────────────────────────────────
#
# **上面那组规则全都用 `(?<!\d)\d{11}(?!\d)` 这种形状，而用户打号码时
# 十有八九会带空格或横杠。** `138 1234 5678` 一个字符都匹配不上，
# 原样落库；而告知那句话（改之前）写着"不会被记录"。
#
# 不去给每条规则加一遍分隔符——那要改五处，而且以后每加一条规则都要记得。
# 做法是**先归一化**：把"数字 + 分隔符 + 数字"这种连续片段里的分隔符去掉，
# 得到一个纯数字串，再拿它去过同一组规则。命中了就整段替换（连分隔符一起），
# 没命中就把原文放回去——**没命中时不留任何痕迹**，
# 否则「我 2016 年买的 300 股」会被改成「我2016年买的300股」，
# 而那是判分要读的内容。
#
# 形状是"数字段 + 分隔符 + 数字段"，至少两段；**总位数 ≥7 才真的替换**，
# 那个判断在 `_collapse_spaced` 里做，不写进正则——写进去要用回溯，
# 而这条正则每一轮都要跑在用户输入上。
#
# `3 点`、`12 万`、`2016 年买的 300 股` 都不满足"分隔符两边都是数字"，
# 一个都不会被卷进来。
_SPACED_DIGITS = re.compile(r"\d+(?:[\s\-‐‑–—]{1,2}\d+)+")

# 住址。省市区 + 路/街/号，或者小区/楼/单元/室——两种形状各抓各的。
# 门牌那一段（数字 + 号/室/栋…）必须要有，只写"北京朝阳"不算住址，
# 那是在说自己在哪个城市，挖掉它没有意义还伤语料。
#
# **中间那几段要允许空格**：用户打地址时空格是常态
# （"建国路 88 号 3 单元"），不允许的话这条规则形同虚设。
#
# 已知代价：开头那个 `[一-龥]{2,8}` 会把紧挨着地址的几个字一起吃掉
# （"我住北京市…" 整段变成 `[住址]`）。要精确切在城市名上得挂一份行政区划表，
# 而那是为了保住两三个字的上下文引入一份要维护的数据。
# **多挖一点好过漏一条地址**，这个方向上的错误是安全的那一侧。
_ADDRESS = re.compile(
    r"[一-龥]{2,8}(?:省|市|区|县|镇|乡)"
    r"[一-龥\d\s]{0,20}?"
    r"(?:路|街|道|巷|村|小区|花园|公寓|大厦|苑|里)"
    r"[一-龥\dA-Za-z\-\s]{0,15}?"
    r"\d+\s*(?:号|栋|幢|座|单元|室|楼|层)"
    r"(?:[一-龥\dA-Za-z\-\s]{0,12}?\d+\s*(?:号|室|楼|层|单元))*"
)

# 小区/楼栋这一种不带省市区，单独一条
_ADDRESS_SHORT = re.compile(
    r"[一-龥]{2,10}(?:小区|花园|公寓|大厦|新村|家属院)"
    r"[一-龥\dA-Za-z\-\s]{0,10}?\d+\s*(?:号|栋|幢|座|单元|室|楼)"
    r"(?:[\dA-Za-z\-\s]{0,8}?\d+\s*(?:号|室|单元)?)*"
)

# 工作单位。**只认自述句式**，理由与姓名那条完全一样：
# 不带句式的话，「启航财经」「王老师的公司」这些剧本内容会被一并挖掉。
_EMPLOYER = re.compile(
    r"(我(?:们)?(?:单位|公司)(?:是|叫)?|我在|本人在|我就职于|我是)\s*"
    r"([一-龥A-Za-z0-9]{2,20}?"
    r"(?:公司|集团|银行|医院|学校|大学|工厂|厂|事业部|研究院|所|局|中心|store|Store))"
    r"(?=(?:上班|工作|做事|干活)|[\s，。,.!！?？、]|$)"
)

# 控制字符。它们进不了 JSON 也进不了日志，而且是最常见的一种投毒载体
_CONTROL = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]")


def _collapse_spaced(text: str) -> str:
    """把带分隔符的长号码折成纯数字，**仅当折完之后确实命中敏感规则**。

    没命中就原样放回。这一条是关键：归一化本身不是目的，
    它只是让 `_RULES` 那五条能看见被空格拆开的号码。
    """
    def repl(match: re.Match) -> str:
        digits = re.sub(r"[^\d]", "", match.group(0))
        # 短的一律放回。7 位以下够不上任何一类敏感号码，而"2016 2017"
        # 这种并列的年份正好落在这一档
        if len(digits) < 7:
            return match.group(0)
        for pattern, placeholder in _NUMBER_RULES:
            if pattern.fullmatch(digits):
                return placeholder
        return match.group(0)

    return _SPACED_DIGITS.sub(repl, text)


# `_RULES` 里纯数字那几条，单独列一份给归一化通道用。
# **不重复写正则**——从 `_RULES` 里挑，两边永远是同一组判据。
_NUMBER_RULES: Tuple[Tuple[re.Pattern, str], ...] = (
    (re.compile(r"\d{17}[\dXx]"), "[身份证]"),
    (re.compile(r"\d{15}"), "[身份证]"),
    (re.compile(r"1[3-9]\d{9}"), "[手机号]"),
    (re.compile(r"\d{13,19}"), "[账号]"),
)


def redact(text: str) -> str:
    """把一段自由文本脱敏到可以落库的程度。

    规则按 `_RULES` 的顺序逐条替换，**顺序有意义**（见那张表里的两处注）。
    输入为空、全空白，一律返回空串——落一条空记录没有意义。

    带分隔符的号码先过一遍归一化（`_collapse_spaced`），否则
    `138 1234 5678` 会一个字符都匹配不上。
    """
    if not text:
        return ""
    cleaned = _CONTROL.sub("", text).strip()
    if not cleaned:
        return ""
    # 归一化要排在最前：它产出的是占位符，之后那几条规则不会再动它
    cleaned = _collapse_spaced(cleaned)
    for pattern, placeholder in _RULES:
        cleaned = pattern.sub(placeholder, cleaned)
    # 住址与单位排在最后：它们的模式里含数字（门牌号），
    # 排在号码规则前面会跟 `\d{13,19}` 抢
    cleaned = _ADDRESS.sub("[住址]", cleaned)
    cleaned = _ADDRESS_SHORT.sub("[住址]", cleaned)
    cleaned = _EMPLOYER.sub(r"\1[单位]", cleaned)
    if len(cleaned) > MAX_CHARS:
        # 截断也要留痕：一条被截过的记录和一条本来就这么短的记录，
        # 在语料里必须能分辨——否则将来标注的人会以为玩家说了半句话
        cleaned = cleaned[:MAX_CHARS] + "…[截断]"
    return cleaned
