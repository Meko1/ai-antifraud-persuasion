"""老陈的每局变体。

同一个剧本，八个不同的人。**为什么必须有这个东西**：作品唯一无法被复制的
资产是"劝阻对象是活的"（docs/REDESIGN-TRAINER.md 调研发现一）。可两个同事
互相截图时如果看到同一句话，"活的"当场破产——变体守的就是这一条。

## 骨架冻结

下面这些每一条在界面上都有对应物，**任何变体都不许碰**：

| 事实 | 界面上的对应物 |
|---|---|
| 三十万、下午三点 | 首页那句"他下午三点前要把三十万转出去"、转账凭证 |
| 王老师 / 启航财经 | 会话列表第二条那个群 |
| 给孩子结婚的钱 | 老伴那条"定金那头又催了一遍" |
| 今早从证券账户划走十万、只剩两万八 | 招商银行那条"支出100,000.00元"、首页那句提醒 |
| 三十万在他银行卡上（投顾看不见） | 首页那句"你看不见" |
| 女儿小雨查过工商，且劝失败了 | 小雨那条 |
| 老伴不知情 | 他瞒着她这件事贯穿全局 |
| 跟了三个月、干了二十年 | 兜底台词库里写死的说法 |

变体只动**他是谁**（工种、老家、怎么被拉进群、赚过多少、婚期多近），
以及**他怎么说话**。骨架一动，首页六条会话与四十条兜底台词会同时穿帮。

## 为什么每个变体自带例句

反面清单（"不用书面语""不写括号动作"）是提示词里最弱的一种约束：模型每
一步都要主动抑制默认文风，一长就漏。例句是最强的。但例句会让输出向它收敛，
这与"不重样"直接冲突——**把例句分散到变体里，两者就不打架了**：
每个玩家的老陈收敛到不同的三句话上。

## 四条轴

拉开距离靠的不是口音，是这四条，按影响体感的大小排：

1. **挡箭牌偏好** —— 他主要拿哪一套挡你（沉没成本 / 从众 / 权威 / 我懂行 / 时间）
2. **软肋** —— 他哪一处一戳就虚。它只改台词，不改判分：效力矩阵与档位映射
   对所有变体是同一份，玩家仍然要读人，只是读的是这一个人。
3. **语言习惯** —— 方言语气词只取三五个，不写成方言剧本；句子长短与标点习惯
4. **具体细节** —— 工种、老家、婚期、账面赚了多少、怎么被拉进群

第 2 条有一处要留神：**所有变体吐出的具体信息量必须相近**。某个变体反复
提到女儿，玩家就更容易引用它去"扎根"，胜率会悄悄上移——那是评审关的资产。
`tools/act_eval.py --drift` 盯的就是这个。
"""

