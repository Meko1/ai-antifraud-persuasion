def persona_for(gid: str, personas: Tuple[Persona, ...] = CHEN_PERSONAS) -> Persona:
    """由对局 id 确定性地取变体。

    不存任何东西：`gid` 本来就在签名令牌里且每轮回传（ADR-0003），
    hash 一下就够。加字段要升令牌版本，而版本一升，所有在玩的局当场作废。

    `personas` 由场景提供（app/scenario.py）。默认值是老陈那一组，
    只为了让老测试与不关心场景的调用方不必改——**新代码请显式传**。
    """
    digest = hashlib.sha256(gid.encode("utf-8")).digest()
    return personas[int.from_bytes(digest[:8], "big") % len(personas)]


def opening_for(gid: str, personas: Tuple[Persona, ...] = CHEN_PERSONAS) -> str:
    """开场白。与变体同源，开场自称什么、后面就得是什么。

    仍然不调模型——「首屏 ≤3 秒」是靠预置台词买的单。
    """
    persona = persona_for(gid, personas)
    digest = hashlib.sha256(f"{gid}:opening".encode("utf-8")).digest()
    return persona.openings[
        int.from_bytes(digest[:8], "big") % len(persona.openings)
    ]
