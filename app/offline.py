# 依据标记。`informed_warning` 与 `bare_assertion` 的分界**只有这一条**：
# 给没给依据（消歧规则 5）。语气强硬、身份权威都不算依据——
# 「我干这行十几年」正是最容易被误当成依据的那一种，它在上面被 scold…
# 不，在 bare_assertion 那一支里被单列。
#
# **按"给理由"这件事的语言形态收，不要按 dev 上出现过哪几句收**——
# 那正是 2026-08-31 第一版栽的跟头：dev 上 100%，留出集上 0%。
_EVIDENCE = re.compile(
    # 因果连接词
    r"因为|由于|之所以|所以说|说明|可见"
    # 举证连接词
    r"|凭这|凭的是|根据|依据|按规定|按流程|这一条|这两条|这几条|从.{0,6}来看|据我所知"
    # 可核验：**"你自己去查得到"是最强的一类依据**
    r"|可以查|查得到|查不到|查一下|可核验|核验|工商|官网|公开(数据|信息|渠道)|有据可查"
    # 全称否定：正规机构从不如何如何
    r"|正规[^，。]{0,8}(不会|从不|都是)|从来不会|从来没有|从不|不会用[^，。]{0,8}发给"
    r"|不会让|没有一家|任何一家|哪一家|不可能|没有人能|谁也不能|哪有"
    # 规律与制度
    r"|固定设计|固定套路|这类平台|这类骗局|通报|规定|法律|监管|流程上"
)


def _has_evidence(utterance: str) -> bool:
    """这句话里给没给依据。见 `_EVIDENCE` 上面那段。"""
    return bool(_EVIDENCE.search(utterance))


# 假设句：「如果这真的是个骗局，你会怎么办呢？」——请他自己设想，不是下判断。
# 少这一道，所有以"万一/如果"开头的苏格拉底式提问都会被记成空口断言，
# 而那是**玩家最该被鼓励的动作之一**被当成失误扣分。
_HYPOTHETICAL = re.compile(r"如果|万一|要是|假如|假设|倘若")

# 选择疑问句：「是 A，还是 B？」。它问的是事实，不是在表态——
# 「清仓这个动作，是您自己决定的，还是群里让这么做的？」里那句
# "您自己决定"是被问的对象，不是被交还的权利。
_ALTERNATIVE_Q = re.compile(r"是.{0,20}，?还是.{0,20}[?？]")

# 否定掉的贬低词不算贬低。**这一条在反诈劝阻里不是边角情况**：
# "被骗不丢人""您不糊涂""这不傻"是这个场景里最该说、也最常说的一类话，
# 而它们逐字包含着责骂词表里的词。
#
# 只看紧挨着的两个字，不做句法分析——"不"离得远就管不着了，
# 那个方向的误差是漏放（该记责骂的记上了），比冤枉玩家便宜。
_NEGATED = re.compile(r"(不|没|别|非|无需|用不着)[^，。！？]{0,2}$")

# **A-不-A 疑问句里的那个"不"不是否定**：「您是不是傻」「你有没有脑子」
# 是反问，是这个表里最典型的责骂形态之一。少了这一条，
# 上面那道否定闸会把它们全放走——`tests/test_offline.py` 当场就红了。
_A_NOT_A = re.compile(r"(.)(不|没)\1[^，。！？]{0,2}$")


def _is_negated(utterance: str, match: "re.Match") -> bool:
    """这次命中是不是被前面的否定词消掉了。"""
    head = utterance[: match.start()]
    if _A_NOT_A.search(head):
        return False
    return bool(_NEGATED.search(head))

# 合规红线。**两条可以同时成立**（消歧规则 0），所以这里不 break。
#
# 2026-08-31 一并放宽：上一版 `unlicensed_advice` 要求"动作词 + 标的词"
# 紧挨着出现，标的词还只有五个，于是实测查全率 0%——
# 「那个板块我不看好，您现在该做的是出来，换个方向」这种**不点名标的
# 却给足了方向**的荐股一条都抓不到，而它恰恰是投顾最容易脱口而出的形态。
_ADVICE_ACT = (
    r"买|卖|加仓|减仓|清仓|平仓|清了|换成|转来买|配置|建仓|调仓|转回|梭"
)
_ADVICE_OBJ = (
    r"这只|那只|票|股|基金|理财|产品|国债|逆回购|货基|债基|组合|板块|指数|仓位|资金"
)

_COMPLIANCE_RULES: Tuple[Tuple[str, re.Pattern], ...] = (
    (
        "unlicensed_advice",
        re.compile(
            rf"({_ADVICE_ACT})[^，。？]{{0,10}}({_ADVICE_OBJ})"
            rf"|({_ADVICE_OBJ})[^，。？]{{0,10}}({_ADVICE_ACT})"
            # 不点名标的，但给了明确方向或判断——荐股不必指名道姓
            r"|不看好|看好.{0,4}(这|那|板块|方向)|该做的是|换个方向|做个组合|给您做个|给你做个"
        ),
    ),
    (
        "guaranteed_return",
        re.compile(
            r"(保证|包管|一定|担保|绝对|肯定)[^，。]{0,8}(赚|不亏|收益|回本|没问题|安全)"
            r"|稳赚|稳的|保本|跑不掉|包赔|亏不了|没风险|零风险|旱涝保收"
            # 承诺弥补亏损，与承诺收益同一条线
            r"|一分(都|钱)?不(少|会少)|给(您|你)补|我补给|算我的|我兜着|我担着"
            r"|不会白干|亏了我|少不了(您|你)|包在我"
        ),
    ),
)

# ── 转述标记：合规红线的免责闸 ─────────────────────────────────────────────
#
# 2026-08-25 补。实测打出这一句：
#
#     「您刚才说他保证下午三点前不转就来不及了，可**保本**又说不承诺收益，
#       这两句能同时成立吗？」
#
# 界面当场弹「合规红线 · 承诺收益」。这是纯粹的误判，而且误判的对象是
# **「指出内部矛盾」这把钥匙的标准打法**——拆矛盾就是要把对方那句"保本"
# 原样端出来。等于产品在惩罚它自己教的最佳动作，还是用作品自称最硬的
# 那个功能惩罚的。
#
# 模型那一侧本来就判得对，`gateway.CLASSIFY_SYSTEM_PROMPT` 消歧规则第 0 条
# 写着「复述或追问老陈自己提到的操作……那是提问，不是建议」。所以这不是
# 新加一条策略，是**把离线这张粗表跟模型那条规则对齐**。
#
# 判据故意取得保守：**只要这句话不是投顾自己在荐、在许，就放过**。
# 这个方向的误差是漏判（玩家真违规了没记上），另一个方向的误差是
# 冤枉玩家——在一个教人怎么说话的产品里，后者贵得多。
#
# ── 2026-08-31：从"只看匹配点之前"改成整句判 ──────────────────────────────
#
# 旧版只扫 `utterance[:match.start()]`，于是标记落在后半句就漏了：
#
#     「清仓这个动作，是您自己决定的，还是**群里**让这么做的？」
#
# ——「群里」在「清仓」后面，闸没生效，一句标准的苏格拉底式提问被记了
# 一条荐股红线。同一批还漏掉两类：
#
#   · **指认**：「但凡承诺稳赚不赔的，都是骗子」——他在骂这句话，不是在说这句话
#   · **质疑**：「稳赚的话，为什么还要您签那份免责协议？」——拆矛盾的标准打法
#
# 后两类和转述是同一件事的三种形态：**这句话里的"稳赚"不是投顾的主张**。
#
# **撇清不在其列**，这是有意的：「稳不稳我不敢说，但我这边给您做个组合」
# 前半句撇清、后半句照样给方向。标注集那条注写得很清楚——
# 撇清不能赦免建议本身。
_QUOTE_MARKERS = re.compile(
    # 转述：这话是别人说的
    r"他说|她说|您说|你说|他保证|老师说|群里|对方说|他讲|所谓|听他|据说|他们说"
    # 指认：这话是骗子的话术，我在指出来
    r"|但凡|凡是|都是骗子|是骗子|是诈骗|骗局|杀猪盘"
    # 质疑：我在拿这话顶他
    r"|打架|对不上|自相矛盾|这两个词|这两件事|能同时成立"
)


def _is_quoted(utterance: str, match: "re.Match") -> bool:
    """这次命中是不是在转述、指认或质疑别人的话，而不是投顾自己的主张。

    整句判，不再只看匹配点之前——理由见上面那段。
    """
    return bool(_QUOTE_MARKERS.search(utterance))

# 扎根：上一轮那句话里的具体成分有没有被拿来用。
# 判据取"两句话共有的、长度 ≥2 的实词片段"，粗但方向是对的——
# 真正的判据在 gateway.CLASSIFY_SYSTEM_PROMPT 里，那是模型的活。
_STOPWORDS = frozenset("的了吗呢吧啊你我他她它们这那是不在有和就都要会说个上下")
_GROUND_MIN = 2

# ── 2026-08-31：两处让"扎根"虚高的漏洞 ────────────────────────────────────
#
# 实测 dev 上误判为扎根的 8 条**全是 parrot 标签**——也就是复读攻略那一类，
# 而扎根门控存在的唯一理由就是拦住它们（§9.2：没有扎根门控，攻略传开
# 当天游戏即报废）。这个方向的错比漏判贵得多。
#
# 撞的是什么，跑一遍就知道：
#
#     「什么」2   「怎么」1   「自己」1   「不能」1
#     「的，」1   「，不」1   「，这」1   「己的」1
#
# 两类，都不是"调参"能解决的，是判据本身漏了：
#
# 1. **标点进了 n-gram。**「的，」「，不」「，这」根本不是词，是没切句留下的
#    渣。上一轮说「这钱是我自己的，我爱怎么弄」，玩家说任何一句带「，不」的话
#    都算扎根——这条路子任何模板句都走得通。
# 2. **功能词二元组。**「什么」「怎么」「自己」「不能」在任何两句中文里都可能
#    同时出现。`_STOPWORDS` 是单字集合，滤得掉「的了」滤不掉「什么」。
#
# 下面这张表按**功能词**收，不是按 dev 上撞了哪几个收——照错例列白名单
# 就是在给这 199 条背答案，换一句没见过的话照样漏。
_STOP_BIGRAMS = frozenset(
    """
    什么 怎么 为什 么办 这样 那样 这些 那些 这个 那个 一个 每个
    自己 我们 你们 他们 她们 大家 别人 人家
    不能 不会 不是 不用 不要 没有 可以 应该 必须 一定 已经 还是
    知道 觉得 认为 告诉 想过 有没 没有 如果 因为 所以 但是 可是
    现在 今天 明天 时候 这次 那次 一下 一点 这么 那么 多少 几个
    """.split()
)

# 句读与空白：切 n-gram 之前一律去掉。留着它们等于把标点也当成实词。
_PUNCT = re.compile(r"[\s，。！？、；：""''「」《》（）,.!?;:\"'()\[\]—…·]+")

