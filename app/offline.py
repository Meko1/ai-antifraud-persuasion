class OfflineGateway:
    """`ModelGateway` 的离线替身。三个业务操作的形状完全一致。

    一个网络请求都不发——这一条由 `tests/test_offline.py` 钉着，
    因为"离线模式其实偷偷在调网关"是这段代码唯一可能的、又最难发现的坏法。
    """

    def __init__(self, rng: Optional[random.Random] = None) -> None:
        self._rng = rng or random.Random()

    async def act(
        self,
        *,
        mood: Mood,
        utterance: str = "",
        scene: Optional[Scenario] = None,
        history: Sequence[Any] = (),
        **_: Any,
    ) -> AsyncIterator[str]:
        # `avoid` 挡的是**看得出来的重复**，窗口取 2 的实测表写在
        # `fallback_line` 的 docstring 里。历史本来就传进来了
        # （`classify` 早就在用），这里只是把它也用上——**服务端不因此
        # 多存任何东西**，最近那两句在签名令牌里（ADR-0003）。
        line = fallback_line(
            mood,
            rng=self._rng,
            scene=scene or DEFAULT,
            avoid="".join(r.reply for r in history[-AVOID_WINDOW:]),
        )
        # 一次吐几个字，好让前端的按句缓冲与打字机效果还是原来那条路径。
        # 一次性整句下发的话，离线模式下的观感与线上差得最远的反而是节奏
        for i in range(0, len(line), 6):
            yield line[i : i + 6]

    async def classify(
        self, *, utterance: str, history: Sequence[Any] = (), opening: str = "", **_: Any
    ) -> str:
        last = history[-1].reply if history else opening
        hits = classify_offline(utterance)
        return json.dumps(
            {"hit_keys": hits, "grounded": grounded_offline(utterance, last)},
            ensure_ascii=False,
        )

    async def narrate_ending(
        self, *, ending: Ending, scene: Optional[Scenario] = None, **_: Any
    ) -> str:
        return "".join(ending_fallback(ending, scene or DEFAULT))


def classify_offline(utterance: str) -> list:
    """关键词分类。

    三条约定见 `_PENALTY_RULES` 上面那段：
    失误压住钥匙、钥匙最多一把、合规红线独立判。
    """
    hits = []

    # 一 · 失误。命中就不再往钥匙里找（消歧规则 3/4/5）。
    #
    # **失误标签彼此可以并存，所以这里不 break**（消歧规则 1：
    # "后面那些失误标签不受此限……也可以彼此并存"）。标注集里
    # 「你清醒一点行不行？他就是个骗子！」正是前半句责骂、后半句空口断言，
    # 两个标签各自独立成立。只有"失误压住钥匙"那一条是收紧的。
    for name, pattern in _PENALTY_RULES:
        m = pattern.search(utterance)
        if not m:
            continue
        # 「这不丢人」「您不糊涂」——否定掉的贬低词不是贬低，见 `_NEGATED`
        if name == "scold" and _is_negated(utterance, m):
            continue
        # 空口断言那一支要再过两道：
        #   · **给了依据就不是空口**，那是有据告知，归下面的钥匙表。
        #     这是两者唯一的分界（消歧规则 5）。
        #   · **假设句不是断言**：「如果这真的是个骗局，你会怎么办呢」
        #     是在请他自己设想，不是在下判断——那是苏格拉底式提问。
        if name == "bare_assertion" and (
            _has_evidence(utterance) or _HYPOTHETICAL.search(utterance)
        ):
            continue
        hits.append(name)

    # 二 · 钥匙，最多一把
    if not hits:
        for name, pattern in _KEY_RULES:
            if not pattern.search(utterance):
                continue
            # 反过来：说了结论却拿不出依据的，不是有据告知，是空口断言
            if name == "informed_warning" and not _has_evidence(utterance):
                hits.append("bare_assertion")
                break
            # 「是您自己决定的，还是群里让这么做的？」问的是决策**来源**，
            # 不是把决定权交还给他。选择疑问句里的"您自己决定"不算支持自主。
            if name == "support_autonomy" and _ALTERNATIVE_Q.search(utterance):
                continue
            hits.append(name)
            break

    # 三 · 合规红线，与上面任何一条并存（消歧规则 0）
    for name, pattern in _COMPLIANCE_RULES:
        m = pattern.search(utterance)
        # 转述或质疑别人的承诺不算自己承诺，见 _QUOTE_MARKERS 那段
        if m and not _is_quoted(utterance, m):
            hits.append(name)
    return hits


def grounded_offline(utterance: str, last_reply: str) -> bool:
    """有没有从上一轮那句话里拿具体成分过来。

    **先去标点再切 n-gram，并滤掉功能词二元组**，理由与实测见
    `_STOP_BIGRAMS` 上面那段。两者都不是调参：留着标点，任何模板句都能
    靠一个「，不」蒙混过关；留着「什么」「怎么」，复读攻略照样判成扎根，
    而那正是这道门控唯一要拦的东西。
    """
    if not last_reply:
        return False
    ref = _PUNCT.sub("", last_reply)
    said = _PUNCT.sub("", utterance)
    grams = {ref[i : i + _GROUND_MIN] for i in range(len(ref) - _GROUND_MIN + 1)}
    grams = {
        g for g in grams
        if not set(g) <= _STOPWORDS and g not in _STOP_BIGRAMS
    }
    return any(g in said for g in grams)
