"""场景。

**这个模块 2026-08-17 才存在。** 在它之前，剧本写死在十五个文件里：
`gateway.SCAM_SCRIPT`、`persona.PERSONAS`、`fallback.LINES`、首页那张客户档案、
`app.js` 的 `TOTAL/PAYEE/PING/PHONE`、安全层的金额豁免、标注集、跑批路线。
想加第二个场景，要在十五处各改一遍，还没有一处能提醒你漏了哪一处。

## 为什么必须有第二个场景

POSITIONING 那三条可检验判据里，只有这一条还没兑现：
**能力可迁移，不是背下一个剧本。** 而判据写得很死——

> **换场景之后效力矩阵必须翻过来。** 两个荐股场景证明不了这一点。

这也正是本模块最要紧的一个字段：`efficacy`。它不是"每个场景配点参数"，
它是这个产品的论点本身：同一张判分表、同一套七把钥匙，在贪驱动的骗局里
和在恐惧驱动的骗局里给出**相反**的最优解。

    锚定这钱本来干什么用的：老陈 1.3（开局最强） → 周阿姨 0.5（帮倒忙）
    指出内部矛盾：        老陈 0.3（早期禁用） → 周阿姨 1.3（早期就该用）

老陈是贪，周阿姨是怕。对贪的人，把抽象收益拉回具体代价最有力；
对怕的人，那只会加重恐慌，真正管用的是拆掉"权威"这个幻觉——
而"公检法不会电话办案、不会有安全账户"是可核验的硬事实，越早说越好。

## 场景**不能**改的东西

判分引擎一行不动：七把钥匙、三项话术失误、两条合规红线、钝化、扎根、
防御姿态、追问窗口、阻力曲线、蓄势池、结局阶梯，全部共用。
场景只提供两样：**演什么**（剧本、人格、台词、界面素材）与
**此刻哪一招管用**（效力矩阵 + 有据告知的退化档位）。

一个场景要是需要新的机制才成立，那说明它不该做成场景，该做成新玩法。
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Dict, Mapping, Optional, Sequence, Tuple

from .persona import CHEN_PERSONAS, ZHOU_PERSONAS, Persona
from .scoring import EFFICACY, Ending, Mood


@dataclass(frozen=True)
class FactRow:
    """客户档案上的一行。带 warn 的那几行是玩家手上的牌。"""

    label: str
    value: str
    note: str = ""
    warn: bool = False


@dataclass(frozen=True)
class PhoneRow:
    """复盘揭晓里他手机上的一条会话。

    `test` 是正则**源码字符串**，随场景下发到前端，由 JS 侧 `new RegExp` 编译。
    判据是"**他**说没说过"——匹配跑在劝阻对象的台词上，与扎根同源。
    """

    avatar: str       # CSS 类名（av-group / av-bank / …）
    initial: str      # 头像上的字，群头像为空
    name: str
    time: str
    line: str
    clue: str
    test: str = ""    # 空 = 这一条本来就在投顾手里，不计入分母
    own: bool = False


@dataclass(frozen=True)
class Scenario:
    """一个骗局场景。"""

    id: str
    name: str            # 复盘与工作台上显示
    kind: str            # 一句话说清它靠什么驱动：贪 / 怕
    script: str          # 注入演绎提示词的骨架（原 SCAM_SCRIPT）
    speaker: str         # 提示词里怎么称呼他（"老陈" / "周淑琴"）
    # 「投顾找上来了，他看得见什么、看不见什么、他会拿什么挡你」。
    # **这一段必须随场景走**：老陈挡你的是沉没成本和从众，周阿姨挡你的是
    # 「办案纪律不许我说」——同一段通用文案套两个场景，第二个当场穿帮。
    context: str
    personas: Tuple[Persona, ...]

    # ── 演绎指示 ──────────────────────────────────────────────────────
    first_turn: str
    moods: Mapping[Mood, str]
    pressure: str
    endings: Mapping[Ending, str]

    # ── 兜底台词（绕过安全层直发，必须自身安全）────────────────────────
    lines: Mapping[Mood, Sequence[str]]
    ending_lines: Mapping[Ending, Sequence[str]]
    waiting: str

    # ── 界面素材 ──────────────────────────────────────────────────────
    peer: str            # 聊天页标题
    # 头像上那个字，以及界面上指代他/她的那个代词。
    # **代词不是细节**：状态条上写着「他现在 烦躁」，而这一局的客户是位阿姨，
    # 玩家一眼就看出这套界面是照另一个人做的。
    initial: str
    pronoun: str
    ping: str            # 投顾发出去的第一条
    client_name: str
    client_sub: str
    client_tag: str
    incident_title: str
    incident_lead: str
    incident_hint: str
    facts: Tuple[FactRow, ...]
    desk_note: Tuple[str, ...]   # 工作台底部那段交底，逐行
    phone: Tuple[PhoneRow, ...]
    total: int
    test_transfer: int
    payee: str
    ending_copy: Mapping[str, Mapping[str, str]]

    # ── 判分：场景唯一能动的两处 ──────────────────────────────────────
    #
    # 缺省沿用全局效力矩阵。只覆写要翻过来的那几把，其余共用——
    # 抄一整张表过来，改判分参数时两张表必然走散。
    efficacy_override: Mapping[str, Mapping[Mood, float]] = field(
        default_factory=dict
    )
    # 「有据告知」在哪几档会退化成空口断言。
    # 老陈是后两档才说得；周阿姨相反，**越早说越好**，所以这里给空元组。
    mistimed_warning_moods: Tuple[Mood, ...] = (Mood.GUARDED, Mood.IRRITATED)

    @property
    def efficacy(self) -> Mapping[str, Mapping[Mood, float]]:
        """本场景实际生效的效力矩阵。"""
        if not self.efficacy_override:
            return EFFICACY
        merged = {k: dict(v) for k, v in EFFICACY.items()}
        for key, row in self.efficacy_override.items():
            merged[key].update(row)
        return merged

    def payload(self) -> Dict[str, Any]:
        """下发给前端的那一份。

        **前端不再写死任何剧本常量。** 金额、收款方、客户档案、揭晓清单
        原先散在 `app.js` 与 `index.html` 里，加第二个场景时那些地方
        没有一处会提醒你漏改了。
        """
        return {
            "id": self.id,
            "name": self.name,
            "peer": self.peer,
            "initial": self.initial,
            "pronoun": self.pronoun,
            "ping": self.ping,
            "waiting": self.waiting,
            "client": {
                "name": self.client_name,
                "sub": self.client_sub,
                "tag": self.client_tag,
                "facts": [
                    {"label": f.label, "value": f.value,
                     "note": f.note, "warn": f.warn}
                    for f in self.facts
                ],
            },
            "incident": {
                "title": self.incident_title,
                "lead": self.incident_lead,
                "hint": self.incident_hint,
            },
            "note": list(self.desk_note),
            "phone": [
                {"avatar": r.avatar, "initial": r.initial, "name": r.name,
                 "time": r.time, "line": r.line, "clue": r.clue,
                 "test": r.test, "own": r.own}
                for r in self.phone
            ],
            "money": {
                "total": self.total,
                "test_transfer": self.test_transfer,
                "payee": self.payee,
            },
            "endings": {k: dict(v) for k, v in self.ending_copy.items()},
        }


