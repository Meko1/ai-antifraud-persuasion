from __future__ import annotations

from typing import Mapping, Optional, Tuple

from .scenarios import ALL, FactRow, PhoneRow, Scenario

__all__ = [
    "DEFAULT", "SCENARIOS", "SCARE_WORDS_OTHER_SCENES",
    "FactRow", "PhoneRow", "Scenario", "scenario_for",
]


SCENARIOS: Tuple[Scenario, ...] = ALL
DEFAULT = SCENARIOS[0]


# 每个场景的招牌说法。**用途只有一个：查串场**。
#
# 起因是 2026-08-23 的 hang 跑批——安全层那句硬编码的荐股兜底
# 「反正老师推的那只，我心里有数」在顾之然那一局出现了 14 次。
# 穿帮不需要整句照抄，**一个"老师"就够了**，所以判据落在词上而不是整句上。
#
# 选词的标准是"另外四个场景里绝不会出现"，宁可少写几个也不要写宽：
# 写宽了会拦住正当的台词，而这张表是给测试用的，误报比漏报更烦人。
_SIGNATURE_WORDS: Mapping[str, Tuple[str, ...]] = {
    "chen": ("老师", "那只票", "内部消息"),
    "zhou": ("办案", "警官", "检察院"),
    "liu": ("沐晴",),
    "ben": ("垫付", "佣金", "刷单"),
    "hang": ("量化", "合约", "提现"),
    # 2026-09-05 补。shao（健康恐吓）2026-09-03 就加进来了，但这张表漏了它——
    # **漏的后果不是少查一个场景，是少查五个**：`SCARE_WORDS_OTHER_SCENES`
    # 由这张表推导，shao 不在键里，它自己那一行整个不存在，
    # 于是"别的场景的招牌词有没有漏进老邵嘴里"这道检查从来没跑过。
    # 选词同上：另外五个场景绝不会出现的词。
    "shao": ("病灶", "疗程", "体检"),
}

# 对每个场景：**别人的**招牌词。测试直接吃这一份。
SCARE_WORDS_OTHER_SCENES: Mapping[str, Tuple[str, ...]] = {
    sid: tuple(w for other, words in _SIGNATURE_WORDS.items() if other != sid
               for w in words)
    for sid in _SIGNATURE_WORDS
}

_BY_ID = {s.id: s for s in SCENARIOS}


def scenario_for(sid: Optional[str]) -> Scenario:
    """按 id 取场景。取不到一律落到默认场景，不抛错。

    `sid` 来自签名令牌（ADR-0003），改不动；但旧令牌里没有这个字段，
    而"旧令牌续玩时崩在这一行"比"落回老陈"糟糕得多。
    """
    return _BY_ID.get(sid or "", DEFAULT)


