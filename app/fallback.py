# 结局台词的兜底。**这一档比逐轮兜底更要紧**：结局是整局的最后一屏，
# 那一次生成失败，玩家会看到判分跳完之后对话直接断掉，连一句收尾都没有。
# 逐轮台词降级还能靠"骗子本来就说车轱辘话"糊过去，最后一屏糊不过去。
#
# 每档只给两句，且必须与 gateway.narrate_ending 里那段指示说的是同一件事——
# 转账凭证那张卡是按结局种类画的，台词说的和卡上写的不能是两回事。
ENDING_LINES: Mapping[Ending, Sequence[str]] = {
    Ending.PERSUADED: (
        "行……我不转了。",
        "你今天要是没找我，这三十万就真没了。",
    ),
    Ending.INTERCEPTED: (
        "我就先转两万试试水，剩下的我按住了。",
        "你别再说了，就当交个学费。",
    ),
    Ending.STALLED: (
        "今天先不转了，我再想想。",
        "你说的我记下了，行了吧。",
    ),
    Ending.TRANSFERRED: (
        "钱我已经转过去了。",
        "这事儿你就别管了。",
    ),
    Ending.BLACKLISTED: (
        "你烦不烦。",
        "以后别再找我了。",
    ),
}

# 排队期间前端显示的等待文案，角色兼容，不是转圈加载
WAITING_LINE = "他正在跟老师打电话…"


def fallback_line(mood: Mood, rng: Optional[random.Random] = None) -> str:
    lines = LINES[mood]
    return (rng or random).choice(list(lines))


def ending_fallback(ending: Ending) -> Sequence[str]:
    """结局台词的兜底。不随机——最后一屏要的是确定，不是花样。"""
    return ENDING_LINES[ending]
