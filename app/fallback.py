def fallback_line(mood: Mood, rng: Optional[random.Random] = None) -> str:
    lines = LINES[mood]
    return (rng or random).choice(list(lines))


def opening_line(rng: Optional[random.Random] = None) -> str:
    return (rng or random).choice(list(OPENING_LINES))
