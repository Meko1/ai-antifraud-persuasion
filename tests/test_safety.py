    """词表里**绝不能收「老陈」「李经理」**。

    他会直呼李经理，也会说"我老陈这辈子"——那是真话不是旁白。收紧到能拦住
    「李经理这句有点戳人」这类第三人称叙述，就一定会误伤上面这几句。
    那一类交给提示词治根，安全层只拦老陈根本不会打的那些词。
    """
    assert screen_sentence(台词) == 台词


