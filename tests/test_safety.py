def test_违规优先于不是他的话() -> None:
    """顺序不能反。

    外链与微信号是最高危的一类，设计上要求**整句替换**成兜底台词——
    丢弃会在对话里留个空档，而按句缓冲的整句替换正是为了不留空档。
    一句同时带角色标签与外链的话，若先判"不是他的话"就会被直接丢掉，
    替换那条路永远走不到。
    """
    assert screen_sentence("user加他微信 stockmaster888 就能进群") == SAFE_FALLBACK


@pytest.mark.parametrize(
    "台词",
    [
        "我今早才划走100000，怎么了。",
        "账上就剩28000了，你满意了吧。",
        "我已经转了50000过去了，怕什么。",
        "那三十万我准备300000一把梭。",
        "我账户里还有80000。",
        "凑了300000，就等今天下午。",
        "转20000试试水行不行。",
        "剩下的15000我明天再转。",
    ],
)
def test_老陈自己的钱不能被当成股票代码(台词: str) -> None:
    """剧本里写死的每一个数字都要过这一关。

    三十万写成 `300000` 是 6 位、十万写成 `100000` 也是 6 位、余额 `28000`
    是 5 位——正好是 A 股与港股代码的形状。这一条曾经真的犯了：
    「我已经转了50000过去了」整句被替换成兜底台词，玩家看到的是一句
    答非所问的话——**整句替换比丢弃更刺眼**。

    **剧本改数字时这张表要跟着改**：加一个新金额，先来这儿加一行。
    """
    assert screen_sentence(台词) == 台词


